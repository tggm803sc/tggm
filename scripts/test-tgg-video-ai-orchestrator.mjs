#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {createStore} from '../tgg-video-ai/store.mjs';
import {createVideoAiOrchestrator} from '../tgg-video-ai/orchestrator.mjs';
import {markManualEdit} from '../tgg-video-ai/timeline-adapter.mjs';
const root=await fs.mkdtemp(path.join(os.tmpdir(),'tgg-video-ai-orch-'));
const store=createStore({root});
const projectEvents=[];
const projectsClient={async postEvent(payload){projectEvents.push(payload);throw new Error('projects_offline');},async saveAsset(payload){projectEvents.push(payload);throw new Error('projects_offline');}};
const orch=createVideoAiOrchestrator({store,projectsClient});
const assets=[{id:'vid1',projectId:'p1',durationMs:10000,type:'video',version:1,uri:'tgg://vid1'},{id:'song1',projectId:'p1',durationMs:10000,type:'audio',version:1,uri:'tgg://song1'}];
const analyzed=await orch.analyzeProject('p1',{assets,signals:{vid1:{shots:[{id:'s1',startMs:0,endMs:4000,score:.9},{id:'s2',startMs:4000,endMs:10000,score:.8}]},song1:{confidence:.9,bpm:120,beats:[0,1000,2000,3000,4000,5000,6000,7000,8000,9000]}}});
assert.equal(analyzed.state,'analyzing-music');
const planned=await orch.planProject('p1',{mode:'music-video',directives:['auto-first-cut','beat-sync'],mediaAnalyses:analyzed.mediaAnalyses,musicAnalysis:analyzed.musicAnalysis});
assert.equal(planned.state,'ready-to-preview');
const applied=await orch.applyPlan('p1',planned.plan.id,{}); assert.equal(applied.timeline.version,1);
const manual=markManualEdit(applied.timeline,{type:'update-clip',itemId:applied.timeline.tracks[0].clips[0].id,patch:{timelineStartMs:250}});
await store.put('timelines',manual.id,manual);
const queued=await orch.queueRender('p1',manual.version,{assets,preset:{width:1920,height:1080,fps:30,container:'mp4',codec:'h264'}});
assert.equal(queued.job.timelineVersion,2); assert.equal(queued.job.status,'queued');
const running={...queued.job,status:'running',progress:42}; await store.put('render-jobs',running.id,running);
const orch2=createVideoAiOrchestrator({store,projectsClient}); const recovered=await orch2.recoverPendingJobs(); const recoveredJob=await store.get('render-jobs',running.id);
assert.equal(recovered.includes(running.id),true); assert.equal(recoveredJob.status,'queued'); assert.notEqual(recoveredJob.status,'succeeded');
const manifest=await store.get('render-manifests',queued.manifest.id);
const done=await orch2.completeRenderJob(running.id,{exists:true,readable:true,manifestHash:manifest.manifestHash,assetId:'out1',metadata:{durationMs:4000,width:1920,height:1080,mimeType:'video/mp4'}});
assert.equal(done.job.status,'succeeded'); assert.equal(done.output.manifestHash,manifest.manifestHash); assert.equal(done.output.timelineVersion,2); assert.equal(projectEvents.length>0,true);
console.log(JSON.stringify({schema:'tgg.video-ai.orchestrator.test.v1',status:'PASS'},null,2));
